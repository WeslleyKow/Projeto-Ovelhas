  await page.getByRole('button', { name: 'Salvar progresso' }).click()
  await page.getByText('Li sobre ciência.').waitFor()
  await page.getByAltText('Foto do progresso').waitFor()
  await page.getByRole('button', { name: 'Excluir registro' }).click()
  await page.getByText('Li sobre ciência.').waitFor({ state: 'detached' })
  await page.getByText('0 / 4 artigos').waitFor()
  await page.evaluate(() => { const data = JSON.parse(localStorage.getItem('juntos-demo')); const goal = data.goals.find(goal => goal.title === 'Ler 4 artigos'); goal.deadline = '2000-01-01'; localStorage.setItem('juntos-demo', JSON.stringify(data)) })
  await enterDemo(page)
  await page.getByRole('button', { name: 'Objetivos' }).first().click()
  await page.getByRole('button', { name: 'Atualizar objetivos' }).click()
  await page.getByText('Objetivos atualizados!').waitFor()
  await page.getByRole('button', { name: 'Multas', exact: true }).first().click()
  await page.getByRole('heading', { name: 'Multas pendentes' }).waitFor()
